from functools import lru_cache
from pathlib import Path

from pydantic import model_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

BACKEND_DIR = Path(__file__).resolve().parents[2]
_DEV_JWT_SECRET = "changeme-development-only-secret"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    # --- App ---
    APP_NAME: str = "Ramsar Wetlands Monitoring API"
    APP_ENV: str = "development"
    API_V1_PREFIX: str = "/api/v1"
    DEBUG: bool = True

    # --- CORS ---
    CORS_ORIGINS: list[str] = ["http://localhost:3000"]

    # --- Database ---
    # PostgreSQL/PostGIS in deployment; sqlite:///./dev.db works for local
    # development without Docker (users + datasets tables only).
    DATABASE_URL: str = "postgresql+psycopg://postgres:postgres@localhost:5432/ramsar_wetlands"

    # --- Redis / Celery ---
    REDIS_URL: str = "redis://localhost:6379/0"

    # --- Auth ---
    JWT_SECRET: str = _DEV_JWT_SECRET
    JWT_ALGORITHM: str = "HS256"
    JWT_ACCESS_TOKEN_EXPIRE_MINUTES: int = 60
    LOGIN_MAX_ATTEMPTS: int = 5
    LOGIN_LOCKOUT_MINUTES: int = 15

    # First administrator, created on startup only while the users table is
    # empty. The password must be changed at first sign-in.
    INITIAL_ADMIN_USERNAME: str | None = None
    INITIAL_ADMIN_PASSWORD: str | None = None

    # --- Datasets ---
    # Every uploaded file is kept here (history / rollback).
    DATA_STORAGE_DIR: Path = BACKEND_DIR / "storage"
    # Published climate files are written here; the portal reads the same
    # folder (frontend CLIMATE_DATA_DIR).
    CLIMATE_PUBLISH_DIR: Path = BACKEND_DIR.parent / "frontend" / "data" / "climate"
    # Ramsar Site list used to validate site numbers in uploads.
    RAMSAR_SITES_FILE: Path = BACKEND_DIR.parent / "frontend" / "data" / "ramsar-sites.json"
    MAX_UPLOAD_MB: int = 25

    # --- Copernicus Data Space / Sentinel Hub ---
    # OAuth client credentials stay on the server; the frontend never sees them.
    COPERNICUS_CLIENT_ID: str | None = None
    COPERNICUS_CLIENT_SECRET: str | None = None
    COPERNICUS_TOKEN_URL: str = (
        "https://identity.dataspace.copernicus.eu/auth/realms/CDSE/protocol/openid-connect/token"
    )
    COPERNICUS_PROCESS_URL: str = "https://sh.dataspace.copernicus.eu/process/v1"
    COPERNICUS_STATISTICS_URL: str = "https://sh.dataspace.copernicus.eu/statistics/v1"
    COPERNICUS_CATALOG_URL: str = "https://sh.dataspace.copernicus.eu/catalog/v1/search"
    COPERNICUS_TIMEOUT_SECONDS: float = 120.0

    # --- Wetland analysis geometry (GEE ROI polygons) ---
    # Maps the 74 GEE ROI assets to Ramsar site numbers.
    GEE_ROI_MANIFEST_FILE: Path = BACKEND_DIR / "data" / "gee-roi-manifest.json"
    # Exported GEE ROI polygons, one GeoJSON file per asset: <asset name>.geojson
    WETLAND_ROI_DIR: Path = BACKEND_DIR / "data" / "roi"

    # --- Analysis result cache (app/services/result_cache.py) ---
    # auto: Redis at REDIS_URL if reachable, else in-process; redis | memory | off.
    RESULT_CACHE_BACKEND: str = "auto"
    RESULT_CACHE_MAX_MEMORY_MB: int = 256
    # Time series (full period ~20-35 s to compute) and map rasters (reused by
    # the GeoTIFF download). Archive data for a past period does not change.
    RESULT_CACHE_TTL_TIMESERIES_SECONDS: int = 12 * 3600
    RESULT_CACHE_TTL_MAP_SECONDS: int = 3600

    # --- Provided ROI dataset (primary water-quality analysis ROI) ---
    # Supplied polygon file, read as-is; its provenance record sits next to it.
    PROVIDED_ROI_FILE: Path = BACKEND_DIR / "data" / "India Ramsar Sites September 2026.geojson"
    PROVIDED_ROI_META_FILE: Path = BACKEND_DIR / "data" / "provided-roi.meta.json"

    # --- Imported ROIs (team-supplied shapefiles, 2026-09-30) ---
    # <ramsar id>.geojson + manifest.json, generated by app.tools.import_roi_shapefiles.
    IMPORTED_ROI_DIR: Path = BACKEND_DIR / "data" / "imported-roi"

    # --- Official Ramsar boundaries (RSIS) ---
    # Raw RSIS WFS responses (unmodified) live under <BOUNDARIES_DIR>/raw/rsis/;
    # the manifest is rebuilt from them by `python -m app.tools.build_boundaries`.
    BOUNDARIES_DIR: Path = BACKEND_DIR / "data" / "boundaries"
    BOUNDARY_MANIFEST_FILE: Path = BACKEND_DIR / "data" / "boundaries" / "boundary-manifest.json"

    # --- Google Earth Engine ---
    EARTH_ENGINE_PROJECT: str | None = None

    # --- S3-compatible object storage ---
    S3_ENDPOINT: str | None = None
    S3_ACCESS_KEY: str | None = None
    S3_SECRET_KEY: str | None = None
    S3_BUCKET: str | None = None
    S3_REGION: str | None = None

    @model_validator(mode="after")
    def _refuse_insecure_production(self) -> "Settings":
        if self.APP_ENV == "production" and self.JWT_SECRET == _DEV_JWT_SECRET:
            raise ValueError("JWT_SECRET must be set to a strong random value in production.")
        return self


@lru_cache
def get_settings() -> Settings:
    return Settings()


settings = get_settings()
